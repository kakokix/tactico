import sys, time, json
from playwright.sync_api import sync_playwright

URL = sys.argv[1] if len(sys.argv) > 1 else 'http://localhost:8765/'
errors = []
def shot(page, name):
    page.screenshot(path=f'tests/out/{name}.png', full_page=False)

with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
    page = ctx.new_page()
    page.on('console', lambda m: errors.append(f'console.{m.type}: {m.text}') if m.type in ('error', 'warning') else None)
    page.on('pageerror', lambda e: errors.append(f'pageerror: {e}'))
    page.goto(URL)
    page.wait_for_selector('text=Nouvelle carrière', timeout=15000)
    time.sleep(0.8)
    shot(page, '01_title')
    page.click('text=Nouvelle carrière')
    page.fill('#mgrname', 'Kakokix')
    page.click('text=Choisir mon club')
    page.wait_for_selector('.cp')
    shot(page, '02_clubs')
    page.locator('.cp').nth(7).click()
    page.wait_for_selector('.sheet')
    time.sleep(0.3)
    shot(page, '03_clubinfo')
    page.locator('button:has-text("Signer à")').click()
    page.wait_for_selector('.hero', timeout=15000)
    time.sleep(0.5)
    shot(page, '04_home')
    # Avancer jusqu'au match
    for i in range(25):
        if page.locator('button.go.match').count():
            break
        if page.locator('.modal').count():
            page.keyboard.press('Escape')
            time.sleep(0.2)
        page.locator('button.go').first.click()
        page.wait_for_timeout(700)
    shot(page, '05_before_match')
    page.locator('button.go').first.click()
    page.wait_for_selector('text=Jouer en direct', timeout=10000)
    time.sleep(0.4)
    shot(page, '06_prematch')
    page.click('text=Jouer en direct')
    page.wait_for_selector('#lv-canvas')
    time.sleep(3.5)
    shot(page, '07_live')
    page.locator('[data-a=lvSpeed][data-v="4"]').click()
    time.sleep(6)
    shot(page, '08_live_fast')
    if page.locator('.modal').count():
        shot(page, '08b_halftime')
        page.locator('[data-a=htTalk]').first.click()
        time.sleep(1)
    page.locator('[data-a=lvTac]').click()
    time.sleep(0.4)
    shot(page, '09_live_tactics')
    page.locator('[data-a=lvResume]').click()
    time.sleep(0.5)
    page.locator('[data-a=lvTab][data-k=stats]').click()
    time.sleep(1)
    shot(page, '10_live_stats')
    page.locator('[data-a=lvEnd]').click()
    page.wait_for_selector('text=Homme du match', timeout=10000)
    time.sleep(0.5)
    shot(page, '11_postmatch')
    page.locator('[data-a=postDone]').click()
    time.sleep(0.5)
    shot(page, '12_home_after')
    for s in ['squad', 'tactics', 'transfers']:
        page.locator(f'.bnav [data-s={s}]').click()
        time.sleep(0.5)
        shot(page, f'13_{s}')
    page.locator('.bnav [data-s=more]').click()
    time.sleep(0.3)
    shot(page, '14_more')
    for s in ['inbox', 'fixtures', 'comps', 'training', 'finances', 'club', 'career', 'world', 'options']:
        page.locator('.bnav [data-s=more]').click()
        time.sleep(0.2)
        page.locator(f'.main [data-s={s}]').click()
        time.sleep(0.5)
        shot(page, f'15_{s}')
    # fiche joueur
    page.locator('.bnav [data-s=squad]').click()
    time.sleep(0.3)
    page.locator('.only-m .li').first.click()
    time.sleep(0.4)
    shot(page, '16_player')
    page.keyboard.press('Escape')
    # mercato : recherche + offre
    page.locator('.bnav [data-s=transfers]').click()
    time.sleep(0.4)
    page.locator('.main .list .li').first.click()
    time.sleep(0.4)
    shot(page, '17_target')
    if page.locator('text=Faire une offre').count():
        page.click('text=Faire une offre')
        time.sleep(0.3)
        shot(page, '18_bid')
        page.click('text=Envoyer l\'offre')
        time.sleep(0.4)
        shot(page, '19_bid_result')
    page.keyboard.press('Escape'); page.keyboard.press('Escape')
    # Bureau
    page.set_viewport_size({'width': 1280, 'height': 820})
    page.locator('.side [data-s=home]').click()
    time.sleep(0.6)
    shot(page, '20_desk_home')
    page.locator('.side [data-s=tactics]').click()
    time.sleep(0.5)
    shot(page, '21_desk_tactics')
    page.locator('.side [data-s=squad]').click()
    time.sleep(0.5)
    shot(page, '22_desk_squad')
    page.locator('.side [data-s=comps]').click()
    time.sleep(0.5)
    shot(page, '23_desk_comps')
    b.close()
print('\n'.join(errors) if errors else 'NO ERRORS')
